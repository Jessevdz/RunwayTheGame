/** Serialises an icon's shapes to SVG child markup for rasterising onto a map. */
export function iconMarkup(name: IconName): string {
  return (ICON_SHAPES[name] as readonly IconShape[])
    .map((s) => {
      if ('d' in s) return `<path d="${s.d}"/>`;
      if ('cx' in s) return `<circle cx="${s.cx}" cy="${s.cy}" r="${s.r}"/>`;
      return `<rect x="${s.x}" y="${s.y}" width="${s.width}" height="${s.height}" rx="${s.rx}"/>`;
    })
    .join('');
}
